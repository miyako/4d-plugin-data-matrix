inline void checkResult(HRESULT result, const char* operation)
{
    if (FAILED(result))
        throw std::runtime_error(std::string(operation) + " failed (HRESULT " +
            std::to_string(static_cast<unsigned long>(result)) + ")");
}

inline std::vector<BYTE> retryProfile()
{
    std::vector<BYTE> profile(132 + 9 * 12);
    auto put32 = [](std::vector<BYTE>& bytes, size_t offset, uint32_t value) {
        for (int i = 3; i >= 0; --i) {
            bytes[offset + i] = static_cast<BYTE>(value);
            value >>= 8;
        }
    };
    auto signature = [](const char* text) {
        return (uint32_t(text[0]) << 24) | (uint32_t(text[1]) << 16) |
               (uint32_t(text[2]) << 8) | uint32_t(text[3]);
    };
    auto fixed = [&](std::vector<BYTE>& bytes, size_t offset, double value) {
        put32(bytes, offset, static_cast<uint32_t>(std::lround(value * 65536)));
    };
    size_t index = 0;
    auto append = [&](const char* name, const std::vector<BYTE>& tag) {
        while (profile.size() % 4) profile.push_back(0);
        put32(profile, 132 + index * 12, signature(name));
        put32(profile, 136 + index * 12, static_cast<uint32_t>(profile.size()));
        put32(profile, 140 + index * 12, static_cast<uint32_t>(tag.size()));
        profile.insert(profile.end(), tag.begin(), tag.end());
        ++index;
    };
    put32(profile, 8, 0x02100000);
    put32(profile, 12, signature("mntr"));
    put32(profile, 16, signature("RGB "));
    put32(profile, 20, signature("XYZ "));
    put32(profile, 24, (2026u << 16) | 1);
    put32(profile, 28, 1u << 16);
    put32(profile, 36, signature("acsp"));
    put32(profile, 40, signature("MSFT"));
    put32(profile, 64, 1);
    fixed(profile, 68, .9642);
    fixed(profile, 72, 1);
    fixed(profile, 76, .8249);
    put32(profile, 128, 9);

    // ICC v2 D50-adapted sRGB colorants, with a gamma 1.8 curve.
    // This is an intensity-retry space, not Apple's Generic RGB profile.
    const char* names[] = {"wtpt", "rXYZ", "gXYZ", "bXYZ"};
    const double xyz[][3] = {
        {.9642, 1, .8249},
        {.4360747, .2225045, .0139322},
        {.3850649, .7168786, .0971045},
        {.1430804, .0606169, .7141733}
    };
    for (size_t i = 0; i < 4; ++i) {
        std::vector<BYTE> tag(20);
        put32(tag, 0, signature("XYZ "));
        for (size_t j = 0; j < 3; ++j) fixed(tag, 8 + j * 4, xyz[i][j]);
        append(names[i], tag);
    }
    for (const char* name : {"rTRC", "gTRC", "bTRC"}) {
        std::vector<BYTE> tag(16);
        put32(tag, 0, signature("curv"));
        put32(tag, 8, 1);
        // ICC v2 stores a single gamma as unsigned 8.8 fixed point.
        tag[12] = 1;
        tag[13] = 205;
        append(name, tag);
    }
    const std::string description = "DMTX retry sRGB primaries gamma 1.8";
    std::vector<BYTE> desc(12 + description.size() + 1 + 78);
    put32(desc, 0, signature("desc"));
    put32(desc, 8, static_cast<uint32_t>(description.size() + 1));
    for (size_t i = 0; i < description.size(); ++i) desc[12 + i] = description[i];
    append("desc", desc);
    const std::string copyright = "Generated by DMTX; MIT license";
    std::vector<BYTE> text(8 + copyright.size() + 1);
    put32(text, 0, signature("text"));
    for (size_t i = 0; i < copyright.size(); ++i) text[8 + i] = copyright[i];
    append("cprt", text);
    while (profile.size() % 4) profile.push_back(0);
    put32(profile, 0, static_cast<uint32_t>(profile.size()));
    return profile;
}

inline std::array<BYTE, 256> createRetryMap()
{
    struct Apartment {
        HRESULT result;
        Apartment() : result(CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED)) {
            if (result != RPC_E_CHANGED_MODE) checkResult(result, "CoInitializeEx");
        }
        ~Apartment() { if (SUCCEEDED(result)) CoUninitialize(); }
    } apartment;
    using Microsoft::WRL::ComPtr;
    ComPtr<IWICImagingFactory> factory;
    checkResult(CoCreateInstance(CLSID_WICImagingFactory, nullptr, CLSCTX_INPROC_SERVER,
        IID_PPV_ARGS(&factory)), "Create WIC factory");
    ComPtr<IWICColorContext> sourceContext, destinationContext;
    checkResult(factory->CreateColorContext(&sourceContext), "Create sRGB context");
    checkResult(sourceContext->InitializeFromExifColorSpace(1), "Initialize sRGB context");
    checkResult(factory->CreateColorContext(&destinationContext), "Create retry context");
    const auto profile = retryProfile();
    checkResult(destinationContext->InitializeFromMemory(profile.data(),
        static_cast<UINT>(profile.size())), "Initialize retry profile");
    std::array<BYTE, 256 * 3> ramp{};
    for (size_t i = 0; i < 256; ++i)
        ramp[i * 3] = ramp[i * 3 + 1] = ramp[i * 3 + 2] = static_cast<BYTE>(i);
    ComPtr<IWICBitmap> source;
    checkResult(factory->CreateBitmapFromMemory(256, 1, GUID_WICPixelFormat24bppRGB,
        static_cast<UINT>(ramp.size()), static_cast<UINT>(ramp.size()), ramp.data(),
        &source), "Create intensity ramp");
    ComPtr<IWICColorTransform> transform;
    checkResult(factory->CreateColorTransformer(&transform), "Create WIC transform");
    checkResult(transform->Initialize(source.Get(), sourceContext.Get(),
        destinationContext.Get(), GUID_WICPixelFormat24bppRGB), "Initialize WIC transform");
    std::array<BYTE, 256 * 3> converted{};
    checkResult(transform->CopyPixels(nullptr, static_cast<UINT>(converted.size()),
        static_cast<UINT>(converted.size()), converted.data()), "Convert intensity ramp");
    std::array<BYTE, 256> map{};
    for (size_t i = 0; i < 256; ++i) map[i] = converted[i * 3];
    return map;
}

// Map a complete 8-bit grayscale buffer through the cached WIC intensity map.
// WIC transforms each neutral intensity independently, so a 256-entry map is
// equivalent to converting a full-size RGB bitmap, without allocating one per
// retry. Throws if WIC is unavailable; the caller treats that as a no-match.
inline std::vector<uint8_t> retryPixels(const std::vector<uint8_t>& original)
{
    static const auto map = createRetryMap();
    std::vector<uint8_t> retry(original.size());
    for (size_t i = 0; i < original.size(); ++i) retry[i] = map[original[i]];
    return retry;
}

